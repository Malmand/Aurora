"""Load and check site.yaml; regenerate the value table in SOURCES.md."""

from __future__ import annotations

import argparse
import re

import yaml

from . import paths

STATUSES = {"verified", "brief_unverified", "computed", "ASSUMPTION", "missing"}
REQUIRED = ("value", "unit", "source", "date", "confidence", "status")
BEGIN = "<!-- BEGIN VALUE TABLE (generated by python -m aurora.data.site --write-sources) -->"
END = "<!-- END VALUE TABLE -->"


def load_site(path=paths.SITE_YAML) -> dict:
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def value(site: dict, key: str):
    """Return a site value; refuse to hand out missing values."""
    e = site["values"][key]
    if e["status"] == "missing" or e["value"] is None:
        raise KeyError(f"site value '{key}' is missing; see data/itbayat/SOURCES.md")
    return e["value"]


def source_keys(md_text: str) -> set[str]:
    return set(re.findall(r"^\s*-\s+\*\*([A-Z0-9_]+)\*\*", md_text, flags=re.M))


def check(site: dict, sources_md: str | None = None) -> list[str]:
    """Return a list of problems; empty means every value is sourced or flagged."""
    problems = []
    known = source_keys(sources_md) if sources_md else None
    for k, e in site["values"].items():
        for r in REQUIRED:
            if r not in e:
                problems.append(f"{k}: missing field '{r}'")
        st = e.get("status")
        if st not in STATUSES:
            problems.append(f"{k}: bad status {st!r}")
        if st == "ASSUMPTION" and "range" not in e and e.get("source") == "ASSUMPTION":
            problems.append(f"{k}: ASSUMPTION without a sensitivity range")
        if st != "missing" and e.get("value") is None:
            problems.append(f"{k}: null value but status {st}")
        if st == "missing" and e.get("value") is not None:
            problems.append(f"{k}: has a value but status 'missing'")
        src = e.get("source")
        if known is not None and src != "ASSUMPTION" and src not in known:
            problems.append(f"{k}: source key {src!r} not listed in SOURCES.md")
    return problems


def value_table(site: dict) -> str:
    """Markdown table of every site value with source, date, confidence and status (for SOURCES.md)."""

    def cell(x):
        s = "" if x is None else str(x)
        return s.replace("|", "/")

    rows = ["| Key | Value | Unit | Source | Date | Confidence | Status | Note |", "|---|---|---|---|---|---|---|---|"]
    for k, e in site["values"].items():
        note = e.get("note", "")
        if "range" in e:
            note = (note + f" Sensitivity range {e['range']}.").strip()
        rows.append(
            "| "
            + " | ".join(
                cell(x)
                for x in (
                    k,
                    e["value"] if e["value"] is not None else "**missing**",
                    e["unit"],
                    e["source"],
                    e["date"],
                    e["confidence"],
                    e["status"],
                    note,
                )
            )
            + " |"
        )
    return "\n".join(rows)


def write_sources(site: dict, path=paths.SOURCES_MD) -> None:
    text = path.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise ValueError("SOURCES.md lacks the value-table markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    path.write_text(head + BEGIN + "\n\n" + value_table(site) + "\n\n" + END + tail, encoding="utf-8")


def main(argv=None):
    """Print the site values, or rewrite the table in SOURCES.md with --write-sources."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write-sources", action="store_true")
    a = ap.parse_args(argv)
    site = load_site()
    if a.write_sources:
        write_sources(site)
    probs = check(site, paths.SOURCES_MD.read_text(encoding="utf-8"))
    counts = {}
    for e in site["values"].values():
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    print("site.yaml status counts:", counts)
    if probs:
        print("\n".join(probs))
        raise SystemExit(1)


if __name__ == "__main__":
    main()

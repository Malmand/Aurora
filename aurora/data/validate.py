"""Site validation report: docs/validation_site.md plus figures/validation_site.{pdf,png}.

Compares the weather products with each other and with transcribed reference
values (PAGASA Basco normals, Tsai et al. 2020, Castro et al. 2022). Missing
products or untranscribed references are reported as pending. Nothing is
filled in.
"""
from __future__ import annotations

import datetime as dt

import numpy as np
import pandas as pd

from . import paths, pvmodel, rawio
from ..plotting import style

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

# PV system for the yield check (ASSUMPTION; Phase 2 fixes the real array)
PV = pvmodel.PV


def full_years(df: pd.DataFrame) -> pd.DataFrame:
    """Keep calendar years with at least 99 % of hours present."""
    s = df.iloc[:, 0]
    loc = s.index.tz_convert(paths.LOCAL_TZ)
    n = s.groupby(loc.year).count()
    exp = pd.Series({y: (366 if pd.Timestamp(y, 12, 31).dayofyear == 366 else 365) * 24 for y in n.index})
    keep = n.index[(n / exp) >= 0.99]
    return df[np.isin(loc.year, keep)]


def monthly_ghi(ghi: pd.Series) -> pd.DataFrame:
    """Monthly mean daily GHI (kWh/m2/day): mean and SD across years."""
    loc = ghi.copy()
    loc.index = loc.index.tz_convert(paths.LOCAL_TZ)
    daily = loc.resample("D").sum(min_count=20) / 1000.0
    ym = daily.groupby([daily.index.year, daily.index.month]).mean()
    ym.index.names = ["year", "month"]
    g = ym.groupby(level="month")
    return pd.DataFrame({"mean": g.mean(), "sd": g.std(), "n_years": g.count()})


def monthly_mean(x: pd.Series) -> pd.DataFrame:
    loc = x.copy()
    loc.index = loc.index.tz_convert(paths.LOCAL_TZ)
    ym = loc.groupby([loc.index.year, loc.index.month]).mean()
    ym.index.names = ["year", "month"]
    g = ym.groupby(level="month")
    return pd.DataFrame({"mean": g.mean(), "sd": g.std(), "n_years": g.count()})


def hourly_stats(test: pd.Series, ref: pd.Series, min_ref=20.0) -> dict:
    d = pd.concat([test, ref], axis=1, keys=["t", "r"]).dropna()
    d = d[d["r"] > min_ref]
    e = d["t"] - d["r"]
    lags = {L: test.corr(ref.shift(L)) for L in range(-2, 3)}
    return dict(n=len(d), ref_mean=d["r"].mean(), mbe=e.mean(), rmse=np.sqrt((e ** 2).mean()),
                mae=e.abs().mean(), r=d["t"].corr(d["r"]),
                best_lag_h=max(lags, key=lags.get))


def pct(a, b):
    return 100.0 * (a - b) / b


def verdict(p, tol_ok=5.0, tol_warn=10.0):
    if p is None or np.isnan(p):
        return "pending"
    a = abs(p)
    return "agrees" if a <= tol_ok else ("acceptable" if a <= tol_warn else "large difference: investigate")


def pv_specific_yield(w: pd.DataFrame, temp: pd.Series, wind: pd.Series | None) -> pd.Series:
    """Annual AC yield (kWh/kWp/yr) per full year for a fixed-tilt array. pvlib, PVWatts."""
    pac = pvmodel.pv_ac_per_kwp(w, temp, wind, PV)
    loc = pac.index.tz_convert(paths.LOCAL_TZ)
    return pac.groupby(loc.year).sum()


def _ref_csv(name):
    p = paths.REF_DIR / name
    if not p.exists():
        return None
    df = pd.read_csv(p)
    return df


def build_report(out_md=paths.DOCS_DIR / "validation_site.md", fig_stem=paths.FIG_DIR / "validation_site"):
    era5 = rawio.read(rawio.ERA5)
    sat = rawio.read(rawio.SATELLITE)
    powr = rawio.read(rawio.NASA_POWER)
    prods = {k: full_years(v) for k, v in {"ERA5": era5, "Satellite": sat, "NASA POWER": powr}.items()
             if v is not None}
    L = [f"# Site validation: Itbayat weather data",
         "",
         f"Generated by `python -m aurora.data.build_itbayat` on {dt.date.today().isoformat()}. "
         "Every product here is a reanalysis or a satellite retrieval. None is a ground measurement. "
         "Statistics use full calendar years only (at least 99 % of hours present).",
         ""]

    L += ["## Data availability", "", "| Product | Status | Full years | Grid point |", "|---|---|---|---|"]
    for name, raw in (("ERA5", era5), ("Satellite", sat), ("NASA POWER", powr)):
        if raw is None:
            L.append(f"| {name} | **not in raw_small/** (run scripts/download_itbayat.py) | - | - |")
        else:
            yrs = sorted(set(prods[name].index.tz_convert(paths.LOCAL_TZ).year))
            gp = (f"{raw.attrs.get('grid_latitude', paths.LAT)}, {raw.attrs.get('grid_longitude', paths.LON)}")
            L.append(f"| {name} | {raw.attrs.get('source', '')} | {yrs[0]}-{yrs[-1]} ({len(yrs)}) | {gp} |")
    L.append("")

    # ---- 1. GHI between products (satellite is the reference) ----
    L += ["## 1. Monthly GHI across products", "",
          "Monthly mean of daily GHI in kWh/m²/day (mean ± SD across years). The satellite product is the reference, "
          "because it observes the clouds; ERA5 and NASA POWER model or derive them.", ""]
    mg = {k: monthly_ghi(v["ghi_wm2"]) for k, v in prods.items()}
    if "Satellite" in mg:
        ref = mg["Satellite"]["mean"]
        hdr = "| Month | " + " | ".join(mg) + " | " + " | ".join(f"{k} vs Sat (%)" for k in mg if k != "Satellite") + " |"
        L += [hdr, "|" + "---|" * (1 + len(mg) + len(mg) - 1)]
        for m in range(1, 13):
            cells = [f"{mg[k].loc[m, 'mean']:.2f} ± {mg[k].loc[m, 'sd']:.2f}" for k in mg]
            diffs = [f"{pct(mg[k].loc[m, 'mean'], ref.loc[m]):+.1f}" for k in mg if k != "Satellite"]
            L.append(f"| {MONTHS[m-1]} | " + " | ".join(cells) + " | " + " | ".join(diffs) + " |")
        ann = {k: v["mean"].mean() for k, v in mg.items()}
        L.append("| **Year** | " + " | ".join(f"**{ann[k]:.2f}**" for k in mg) + " | "
                 + " | ".join(f"**{pct(ann[k], ann['Satellite']):+.1f}**" for k in mg if k != "Satellite") + " |")
        L.append("")
        for k in mg:
            if k != "Satellite":
                p = pct(ann[k], ann["Satellite"])
                L.append(f"- **{k} vs satellite, annual GHI: {p:+.1f} %, {verdict(p)}.**")
        L.append("")
        L += ["Hourly comparison, hours with satellite GHI > 20 W/m²:", "",
              "| Product | n hours | MBE (W/m²) | MAE (W/m²) | RMSE (W/m²) | rMBE (%) | rRMSE (%) | r | best lag (h) |",
              "|---|---|---|---|---|---|---|---|---|"]
        for k in prods:
            if k == "Satellite":
                continue
            s = hourly_stats(prods[k]["ghi_wm2"], prods["Satellite"]["ghi_wm2"])
            L.append(f"| {k} | {s['n']} | {s['mbe']:+.1f} | {s['mae']:.1f} | {s['rmse']:.1f} | "
                     f"{100*s['mbe']/s['ref_mean']:+.1f} | {100*s['rmse']/s['ref_mean']:.1f} | {s['r']:.3f} | {s['best_lag_h']:+d} |")
        L += ["", "A best lag of 0 h confirms that both series use the same hour-ending time label. "
              "NASA POWER is re-labelled from hour-start to hour-ending at download.", ""]
    else:
        L += ["Pending: satellite series not available.", ""]

    # ---- 2. Temperature vs PAGASA Basco normals ----
    L += ["## 2. Temperature vs PAGASA Basco normals (2001-2020)", ""]
    pag = _ref_csv("pagasa_basco_normals_1991_2020.csv")
    tprods = {k: monthly_mean(v["temp_c"]) for k, v in prods.items() if "temp_c" in v}
    have_pag = pag is not None and pag["tmean_c"].notna().all()
    if tprods:
        cols = list(tprods)
        hdr = "| Month | " + " | ".join(f"{k} (°C)" for k in cols) + " | PAGASA Basco (°C) | " + \
              " | ".join(f"{k} − PAGASA (°C)" for k in cols) + " |"
        L += [hdr, "|" + "---|" * (2 + 2 * len(cols))]
        for m in range(1, 13):
            pv = float(pag.loc[pag["month"] == m, "tmean_c"].iloc[0]) if have_pag else np.nan
            cells = [f"{tprods[k].loc[m, 'mean']:.1f}" for k in cols]
            d = [f"{tprods[k].loc[m, 'mean'] - pv:+.1f}" if have_pag else "pending" for k in cols]
            L.append(f"| {MONTHS[m-1]} | " + " | ".join(cells) + f" | {pv if have_pag else 'pending'} | " + " | ".join(d) + " |")
        L.append("")
        if have_pag:
            for k in cols:
                bias = np.mean([tprods[k].loc[m, "mean"] - float(pag.loc[pag["month"] == m, "tmean_c"].iloc[0]) for m in range(1, 13)])
                L.append(f"- **{k} vs PAGASA, annual mean temperature: {bias:+.1f} °C, "
                         f"{'agrees' if abs(bias) <= 1 else 'investigate'}** (tolerance ±1 °C).")
            L.append("- Part of any warm bias is expected: the Basco station sits at 167 m (about 1 °C cooler than "
                     "sea level at a standard lapse rate), the gridded products are ocean-dominated, and they cover "
                     "2015 onwards while the normals cover 2001-2020. The PDF is headed 2001-2020 although its URL says 1991-2020.")
        else:
            L.append("- **Pending.** `data/itbayat/reference/pagasa_basco_normals_1991_2020.csv` is not yet transcribed "
                     "(the PAGASA host was blocked from the cloud session). Years also differ: normals are 1991-2020, "
                     "products here start in 2015.")
        if "NASA POWER" in tprods and "ERA5" not in tprods:
            L.append("- NASA POWER T2M is MERRA-2 at about 0.5° × 0.625°, mostly ocean around Itbayat. "
                     "It damps the diurnal range, so a station comparison will show a smaller Tmax − Tmin.")
        L.append("")
    else:
        L += ["Pending: no temperature series available.", ""]

    # ---- 3. Solar resource vs Tsai et al. (2020) ----
    L += ["## 3. Solar resource vs Tsai et al. (2020)", ""]
    tsai = _ref_csv("tsai2020_solar.csv")
    if tsai is not None and tsai["ghi_kwh_m2_day"].notna().any() and mg:
        L += ["| Month | Tsai 2020 | " + " | ".join(f"{k} (%)" for k in mg) + " |", "|" + "---|" * (2 + len(mg))]
        for m in range(1, 13):
            tv = tsai.loc[tsai["month"] == m, "ghi_kwh_m2_day"].iloc[0]
            L.append(f"| {MONTHS[m-1]} | {tv} | " + " | ".join(
                f"{pct(mg[k].loc[m, 'mean'], tv):+.1f}" if pd.notna(tv) else "-" for k in mg) + " |")
        L.append("")
    else:
        L += ["- Tsai et al. (2020) give monthly GHI only as a chart, so only the annual value is compared. "
              "Their site is Batan Island (Basco), about 45 km from Itbayat.", ""]
        for k in mg:
            ann = float(mg[k]["mean"].mean())
            p_ = pct(ann, 5.14)
            L.append(f"- **{k} annual mean {ann:.2f} kWh/m²/day vs Tsai et al. 5.14 kWh/m²/day "
                     f"(1,876 kWh/m²/yr): {p_:+.1f} %, {verdict(p_)}.**")
        L.append("")

    # ---- 4. PV yield ----
    L += ["## 4. Annual PV specific yield", "",
          f"Fixed array, tilt {PV['tilt']:.0f}°, facing south, PVWatts DC (γ = {PV['gamma_pdc']} /°C), "
          f"SAPM open-rack cell temperature, {PV['losses_frac']*100:.0f} % DC losses, inverter efficiency "
          f"{PV['inv_eff']:.2f}, Hay-Davies transposition (pvlib). These are ASSUMPTIONs for a check, "
          "not the design array.", ""]
    temp_src = prods.get("ERA5")  # ERA5 temperature downstream (agrees with PAGASA; POWER runs warm)
    yields = {}
    if temp_src is not None:
        wind = prods["ERA5"]["wind_ms"] if "ERA5" in prods else None
        for k, v in prods.items():
            if {"ghi_wm2", "dni_wm2", "dhi_wm2"} <= set(v.columns):
                yields[k] = pv_specific_yield(v, temp_src["temp_c"], wind)
        L += ["| Product | Mean (kWh/kWp/yr) | Min | Max | Years |", "|---|---|---|---|---|"]
        for k, y in yields.items():
            L.append(f"| {k} | {y.mean():.0f} | {y.min():.0f} | {y.max():.0f} | {len(y)} |")
        L.append("")
        tname = "ERA5"
        L.append(f"Air temperature from {tname}; wind {'from ERA5' if wind is not None else 'fixed at 1 m/s (no ERA5)'}.")
        L.append("")
    cas = _ref_csv("castro2022_itbayat.csv")
    cy = None
    if cas is not None:
        r = cas.loc[cas["field"] == "pv_specific_yield_kwh_per_kwp", "value"]
        cy = float(r.iloc[0]) if len(r) and pd.notna(r.iloc[0]) else None
    if cy and yields:
        for k, y in yields.items():
            p = pct(y.mean(), cy)
            L.append(f"- **{k} yield vs Castro et al. (2022) {cy:.0f} kWh/kWp/yr: {p:+.1f} %, {verdict(p, 7.5, 15)}.**")
    else:
        L.append("- **Pending vs Castro et al. (2022).** `data/itbayat/reference/castro2022_itbayat.csv` is not yet "
                 "transcribed (Mendeley Data host blocked from the cloud session).")
    L.append("")

    # ---- figure ----
    if mg:
        _figure(mg, tprods, pag if have_pag else None, fig_stem)
        L += ["## Figure", "", f"![Validation](../figures/{fig_stem.name}.png)", "",
              "**Figure.** (A) Monthly mean daily GHI by product, mean ± 1 SD across full years. "
              "(B) Monthly mean air temperature by product" + (" with PAGASA Basco normals." if have_pag else
              "; PAGASA normals pending transcription."), ""]

    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out_md


def _figure(mg, tprods, pag, stem):
    import matplotlib.pyplot as plt
    style.apply()
    c = {"Satellite": style.OKABE_ITO["black"], "ERA5": style.OKABE_ITO["blue"],
         "NASA POWER": style.OKABE_ITO["orange"], "PAGASA": style.OKABE_ITO["vermillion"]}
    mk = {"Satellite": "o", "ERA5": "s", "NASA POWER": "^", "PAGASA": "D"}
    ls = {"Satellite": "-", "ERA5": "--", "NASA POWER": ":", "PAGASA": "-."}
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 2.6))
    x = np.arange(1, 13)
    off = {"Satellite": 0.0, "ERA5": -0.15, "NASA POWER": 0.15}
    ax = axes[0]
    for k, d in mg.items():
        ax.errorbar(x + off.get(k, 0), d["mean"], yerr=d["sd"], color=c[k], marker=mk[k], ls=ls[k],
                    ms=3, capsize=1.5, elinewidth=0.6, label=k)
    ax.set_ylabel("GHI (kWh m$^{-2}$ day$^{-1}$)")
    ax.set_xlabel("Month")
    ax.set_xticks(x, [m[0] for m in MONTHS])
    ax.legend(loc="lower center")
    style.panel_label(ax, "A")
    ax = axes[1]
    for k, d in tprods.items():
        ax.errorbar(x + off.get(k, 0), d["mean"], yerr=d["sd"], color=c[k], marker=mk[k], ls=ls[k],
                    ms=3, capsize=1.5, elinewidth=0.6, label=k)
    if pag is not None:
        ax.plot(x, pag["tmean_c"], color=c["PAGASA"], marker=mk["PAGASA"], ls=ls["PAGASA"], ms=3,
                label="PAGASA Basco 1991-2020")
    ax.set_ylabel("Air temperature (°C)")
    ax.set_xlabel("Month")
    ax.set_xticks(x, [m[0] for m in MONTHS])
    ax.legend(loc="lower center")
    style.panel_label(ax, "B")
    fig.tight_layout()
    style.save(fig, stem)


if __name__ == "__main__":
    print(build_report())
